import { expect, test, type Page } from '@playwright/test'
import { randomUUID } from 'node:crypto'

const prefix = (process.env.FUCHENG_BASE_PATH ?? '').replace(/\/$/, '')
const url = (path: string) => prefix + path
const responseRows = async (page: Page, deleted = false) => (await page.request.get(url(`/api/admin/announcements?deleted=${deleted}`))).json()

async function login(page: Page) {
  await page.goto(url('/admin/announcements'))
  await page.getByLabel('帳號', { exact: true }).fill('e2e-admin')
  await page.getByLabel('密碼', { exact: true }).fill(process.env.FUCHENG_E2E_ADMIN_PASSWORD!)
  await page.getByRole('button', { name: '登入', exact: true }).click()
  await expect(page.getByRole('button', { name: '新增公告', exact: true })).toBeVisible()
  const me = await (await page.request.get(url('/api/auth/me'))).json()
  return { 'X-CSRF-Token': me.csrf_token }
}

async function selectAnnouncement(page: Page, title: string, mobile: boolean) {
  if (mobile && await page.getByRole('button', { name: '← 返回公告清單（保留輸入）' }).isVisible()) {
    await page.getByRole('button', { name: '← 返回公告清單（保留輸入）' }).click()
  }
  await page.locator('.announcement-row').filter({ has: page.getByText(title, { exact: true }) }).click()
}

test('公告可下架、取消刪除、未知結果原樣重試、還原後另行發布', async ({ page, browser }, info) => {
  const headers = await login(page)
  const mobile = info.project.name === 'mobile'
  const title = `合成公告回收-${info.project.name}-${prefix ? 'prefix' : 'root'}`
  await page.getByRole('button', { name: '新增公告', exact: true }).click()
  await page.getByLabel('公告標題').fill(title)
  await page.getByLabel('公告內容', { exact: true }).fill('保留文字與圖片的公告')
  await page.getByRole('button', { name: '儲存公告', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('公告已儲存')
  const item = (await responseRows(page)).find((r: { title: string }) => r.title === title)
  // An inline upload advances the editor's local version before the manager's selected row changes.
  const synthetic = { name: 'synthetic.png', mimeType: 'image/png', buffer: await page.screenshot() }
  await page.getByRole('button', { name: '插入圖片' }).click()
  await page.getByLabel('選擇內文圖片').setInputFiles(synthetic)
  await expect(page.getByLabel('公告內容', { exact: true }).locator('figure img')).toHaveCount(1)
  const inlineId = await page.getByLabel('公告內容', { exact: true }).locator('figure').getAttribute('data-media-id')
  await page.getByRole('button', { name: '儲存公告', exact: true }).click()
  await page.getByRole('switch', { name: '公開到首頁', exact: true }).click()
  await expect(page.getByRole('switch', { name: '公開到首頁', exact: true })).toBeChecked()
  const context = await browser.newContext({ baseURL: info.project.use.baseURL, viewport: info.project.use.viewport, isMobile: info.project.use.isMobile })
  const visitor = await context.newPage()
  await visitor.goto(url('/'))
  await expect(visitor.getByRole('heading', { name: title, exact: true })).toBeVisible()
  expect((await visitor.request.get(url(`/api/public/announcement-media/${inlineId}`))).status()).toBe(200)
  await page.getByRole('switch', { name: '公開到首頁', exact: true }).click()
  await expect(page.getByRole('switch', { name: '公開到首頁', exact: true })).not.toBeChecked()
  await visitor.reload()
  await expect(visitor.getByRole('heading', { name: title, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '插入圖片' }).click()
  await page.getByLabel('選擇內文圖片').setInputFiles(synthetic)
  await expect(page.getByLabel('公告內容', { exact: true }).locator('figure')).toHaveCount(2)
  const before = (await responseRows(page)).find((r: { id: string }) => r.id === item.id)
  await page.getByLabel('公告標題').fill(title + '未儲存輸入')
  await page.getByRole('button', { name: '刪除公告', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '確認刪除公告？', exact: true })
  await expect(dialog).toContainText(title)
  await expect(dialog).toContainText('尚未儲存的輸入不會保存')
  await expect(dialog.getByRole('button', { name: '保留公告', exact: true })).toBeFocused()
  expect(await dialog.evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight })).toBe(true)
  await page.screenshot({ path: info.outputPath('announcement-delete-confirmation.png') })
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByLabel('公告標題')).toHaveValue(title + '未儲存輸入')
  await page.getByRole('button', { name: '刪除公告', exact: true }).click()
  await dialog.getByRole('button', { name: '保留公告', exact: true }).click()
  expect((await responseRows(page)).find((r: { id: string }) => r.id === item.id)).toEqual(before)
  // The write commits, then its response disappears. The retry must carry the identical key and version.
  const operations: unknown[] = []
  await page.route('**/api/admin/announcements/*/delete', async route => {
    operations.push(route.request().postDataJSON())
    if (operations.length === 1) { await route.fetch(); await route.abort('failed') }
    else await route.continue()
  })
  await page.getByRole('button', { name: '刪除公告', exact: true }).click()
  await dialog.getByRole('button', { name: '確認刪除', exact: true }).click()
  await expect(dialog).toContainText('操作結果尚未確認')
  await expect(dialog.getByRole('button', { name: '保留公告', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '原樣重試核對結果', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('公告已刪除')
  expect(operations).toHaveLength(2)
  expect(operations[1]).toEqual(operations[0])
  await page.unroute('**/api/admin/announcements/*/delete')
  await expect(page.getByRole('heading', { name: '已刪除公告', exact: true })).toBeVisible()
  await expect(page.getByLabel('公告標題')).toHaveValue(title)
  await expect(page.getByLabel('公告標題')).toHaveAttribute('readonly', '')
  await expect(page.getByRole('button', { name: '儲存公告', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '插入圖片', exact: true })).toHaveCount(0)
  await expect(page.getByRole('switch')).toHaveCount(0)
  await expect(page.locator('.announcement-editor-pane figure img')).toBeVisible()
  expect((await visitor.request.get(url(`/api/public/announcement-media/${inlineId}`))).status()).toBe(404)
  expect((await page.request.get(url(`/api/admin/announcement-media/${inlineId}`))).status()).toBe(200)
  await page.getByRole('button', { name: '公告修改歷史', exact: true }).click()
  await expect(page.locator('.announcement-editor-pane li').filter({ hasText: '・刪除・' })).toHaveCount(1)
  await expect(page.locator('.announcement-editor-pane figure img')).toBeVisible()
  await page.screenshot({ path: info.outputPath('announcement-deleted-readonly.png'), fullPage: true })
  await selectAnnouncement(page, title, mobile)
  await page.getByRole('button', { name: '還原公告', exact: true }).click()
  const restore = page.getByRole('dialog', { name: '確認還原公告？', exact: true })
  await expect(restore).toContainText('維持未發布')
  await restore.getByRole('button', { name: '維持刪除', exact: true }).click()
  await expect(page.getByRole('heading', { name: '已刪除公告', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '還原公告', exact: true }).click()
  await restore.getByRole('button', { name: '確認還原', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('公告已還原，尚未發布到首頁')
  await expect(page.getByRole('switch', { name: '公開到首頁', exact: true })).not.toBeChecked()
  await expect(page.getByLabel('公告內容', { exact: true })).toContainText('保留文字與圖片的公告')
  await visitor.reload()
  await expect(visitor.getByRole('heading', { name: title, exact: true })).toHaveCount(0)
  await page.getByRole('switch', { name: '公開到首頁', exact: true }).click()
  await expect(page.getByRole('switch', { name: '公開到首頁', exact: true })).toBeChecked()
  await visitor.reload()
  await expect(visitor.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(visitor.locator('.news-card').filter({ hasText: title }).locator('figure img')).toBeVisible()
  const audits = await (await page.request.get(url(`/api/admin/announcements/${item.id}/history`))).json()
  expect(audits.filter((r: { action: string }) => r.action === 'delete')).toHaveLength(1)
  expect(audits.filter((r: { action: string }) => r.action === 'restore')).toHaveLength(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('announcement-restored-published.png'), fullPage: true })
  await context.close()
})

test('公告版本衝突與交錯重試保留草稿、不誤報目前狀態', async ({ page }, info) => {
  const headers = await login(page)
  const title = `合成公告衝突-${info.project.name}-${prefix ? 'prefix' : 'root'}`
  const draft = { title, body: '原公告', is_published: false, is_pinned: false, request_id: randomUUID() }
  const created = await page.request.post(url('/api/admin/announcements'), { headers, data: draft })
  expect(created.status()).toBe(201)
  const item = await created.json()
  const endpoint = url(`/api/admin/announcements/${item.id}`)
  await page.reload()
  await selectAnnouncement(page, title, info.project.name === 'mobile')
  await page.getByLabel('公告標題').fill(title + '本機草稿')
  await page.getByLabel('公告內容', { exact: true }).fill('衝突時仍保留的內容')
  expect((await page.request.put(endpoint, { headers, data: { ...draft, version: 1, body: '另一管理員已更新', request_id: randomUUID() } })).status()).toBe(200)
  await page.getByRole('button', { name: '刪除公告', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '確認刪除', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('公告已被其他管理員更新')
  await expect(page.getByLabel('公告標題')).toHaveValue(title + '本機草稿')
  await expect(page.getByLabel('公告內容', { exact: true })).toHaveText('衝突時仍保留的內容')
  await page.getByRole('button', { name: '儲存公告', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('公告已被其他管理員更新')
  await expect(page.getByLabel('公告內容', { exact: true })).toHaveText('衝突時仍保留的內容')
  await selectAnnouncement(page, title, info.project.name === 'mobile')
  await expect(page.getByLabel('公告內容', { exact: true })).toHaveText('另一管理員已更新')
  await page.getByLabel('公告標題').fill(title + '重試前草稿')
  let calls = 0
  const operations: unknown[] = []
  await page.route('**/api/admin/announcements/*/delete', async route => {
    calls++; operations.push(route.request().postDataJSON())
    if (calls === 1) {
      const committed = await (await route.fetch()).json()
      expect((await page.request.post(endpoint + '/restore', { headers, data: { version: committed.version, request_id: randomUUID(), confirmed: true } })).status()).toBe(200)
      await route.abort('failed')
    } else await route.continue()
  })
  await page.getByRole('button', { name: '刪除公告', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '確認刪除', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('操作結果尚未確認')
  await page.getByRole('dialog').getByRole('button', { name: '原樣重試核對結果', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('公告狀態後續又被變更')
  await expect(page.getByRole('status')).toHaveCount(0)
  await expect(page.getByLabel('公告標題')).toHaveValue(title + '重試前草稿')
  expect(operations).toHaveLength(2); expect(operations[1]).toEqual(operations[0])
  const current = (await responseRows(page)).find((r: { id: string }) => r.id === item.id)
  expect(current.deleted_at).toBeNull(); expect(current.is_published).toBe(false); expect(current.body).toBe('另一管理員已更新')
  await page.screenshot({ path: info.outputPath('announcement-conflict-draft-preserved.png'), fullPage: true })
})

test('內文圖片未知結果遇他人更新，重試不採新版本覆寫', async ({ page }, info) => {
  const headers = await login(page)
  const title = `合成圖片交錯-${info.project.name}-${prefix ? 'prefix' : 'root'}`
  const original = { title, body: '原始內容', body_format: 'plain', is_published: false, is_pinned: false, request_id: randomUUID() }
  const created = await page.request.post(url('/api/admin/announcements'), { headers, data: original })
  expect(created.status()).toBe(201)
  const item = await created.json()
  const endpoint = url(`/api/admin/announcements/${item.id}`)
  await page.reload()
  await selectAnnouncement(page, title, info.project.name === 'mobile')
  await page.getByLabel('公告內容', { exact: true }).fill('本機仍未儲存的圖片草稿')
  const attempts: { version?: string; key?: string }[] = []
  await page.route('**/api/admin/announcements/*/images', async route => {
    const data = route.request().postData()!
    attempts.push({ version: /name="version"\r\n\r\n([^\r]+)/.exec(data)?.[1], key: /name="request_id"\r\n\r\n([^\r]+)/.exec(data)?.[1] })
    if (attempts.length === 1) {
      const committed = await (await route.fetch()).json()
      expect(committed.announcement.version).toBe(2)
      expect((await page.request.put(endpoint, { headers, data: { ...original, version: 2, body: '另一管理員的最新內容', request_id: randomUUID() } })).status()).toBe(200)
      await route.abort('failed')
    } else await route.continue()
  })
  await page.getByRole('button', { name: '插入圖片', exact: true }).click()
  await page.getByLabel('選擇內文圖片').setInputFiles({ name: 'synthetic.png', mimeType: 'image/png', buffer: await page.screenshot() })
  await expect(page.getByRole('alert')).toContainText('結果尚未確認')
  await expect(page.getByRole('button', { name: '儲存公告', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '原樣重試圖片上傳', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('圖片操作已完成，但公告後續又被變更')
  expect(attempts).toHaveLength(2)
  expect(attempts[0].version).toBe('1'); expect(attempts[0].key).toBeTruthy(); expect(attempts[1]).toEqual(attempts[0])
  await expect(page.getByLabel('公告內容', { exact: true })).toHaveText('本機仍未儲存的圖片草稿')
  await expect(page.getByLabel('公告內容', { exact: true }).locator('figure')).toHaveCount(0)
  await page.getByRole('button', { name: '儲存公告', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('公告已被其他管理員更新')
  const current = (await responseRows(page)).find((row: { id: string }) => row.id === item.id)
  expect(current.body).toBe('另一管理員的最新內容'); expect(current.version).toBe(3)
  const history = await (await page.request.get(endpoint + '/history')).json()
  expect(history.filter((row: { action: string }) => row.action === 'inline_photo')).toHaveLength(1)
})
