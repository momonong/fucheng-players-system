import { expect, test } from '@playwright/test'
import { writeFile } from 'node:fs/promises'
const prefix=(process.env.FUCHENG_BASE_PATH??'').replace(/\/$/,'')
test.setTimeout(60_000)
const url=(p:string)=>prefix+p

test('雙身分報名連動：既開管理端讀回、正候補餐食安排、取消遞補與重報',async({page,browser},info)=>{
  const observations:any={prefix,viewport:info.project.name,events:[]}
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(url('/admin/competitions'))
  await page.getByLabel('帳號',{exact:true}).fill('e2e-admin')
  await page.getByLabel('密碼',{exact:true}).fill(process.env.FUCHENG_E2E_ADMIN_PASSWORD!)
  await page.getByRole('button',{name:'登入',exact:true}).click()
  await expect(page.getByRole('button',{name:'登出',exact:true})).toBeVisible()
  const auth=await (await page.request.get(url('/api/auth/me'))).json(),headers={'X-CSRF-Token':auth.csrf_token}
  const create=async(name:string)=>{
    const r=await page.request.post(url('/api/admin/competitions'),{headers,data:{name,competition_date:'2099-10-22',registration_deadline:'2099-10-21T00:00:00+08:00',capacity:1,status:'open',notes:'全新合成雙身分連動驗證'}})
    expect(r.status()).toBe(201);return r.json()
  }
  const comp=await create(`雙身分連動-${info.project.name}-${prefix?'prefix':'root'}`)
  const other=await create(`雙身分切場-${info.project.name}-${prefix?'prefix':'root'}`)
  await page.reload();await page.getByLabel('選擇比賽',{exact:true}).selectOption(comp.id)
  const area=page.getByRole('region',{name:'當次比賽級數安排'})
  await expect(area.getByRole('heading',{name:comp.name,exact:true})).toBeVisible()
  const endpoint=url(`/api/admin/competitions/${comp.id}`)
  const detail=async()=>await(await page.request.get(endpoint)).json()
  const state=async()=>await(await page.request.get(endpoint+'/arrangement')).json()
  await expect.poll(async()=>!!(await state()).layout).toBe(true)
  const initial=await state(),column=initial.layout.columns.find((c:any)=>c.level===2)
  const deleted=await page.request.post(endpoint+'/arrangement/operations',{headers,data:{request_id:crypto.randomUUID(),state_token:initial.state_token,layout_schema_version:2,operation:{action:'delete_column',axis_id:column.id,confirmed_text:false}}})
  expect(deleted.status()).toBe(200)
  await page.getByRole('button',{name:'報名與設定',exact:true}).click()
  const summary=(label:string)=>page.locator('.summary-card').filter({hasText:label})
  await expect(summary('正取／名額')).toContainText('0/1')
  const visitorContext=await browser.newContext({baseURL:info.project.use.baseURL,viewport:info.project.use.viewport,isMobile:info.project.use.isMobile,hasTouch:info.project.use.hasTouch})
  const visitor=await visitorContext.newPage()
  visitor.on('pageerror',e=>errors.push(e.message))
  const register=async(note:'東區'|'西區',diet:'葷食'|'素食',status:'正取'|'候補')=>{
    await visitor.goto(url(`/register/${comp.id}`))
    await visitor.getByLabel('搜尋姓名',{exact:true}).fill('合成同名')
    await expect(visitor.locator('.public-candidates button')).toHaveCount(2)
    await visitor.getByRole('button',{name:`合成同名 ${note}`,exact:true}).click()
    await visitor.getByRole('radio',{name:diet,exact:true}).check()
    await visitor.getByRole('button',{name:'確認以 合成同名 報名',exact:true}).click()
    await expect(visitor.getByRole('status')).toHaveText('報名完成')
    await expect(visitor.locator('.registration-receipt')).toContainText(`合成同名（${note}）`)
    await expect(visitor.locator('.receipt-status')).toHaveText(status)
    await expect(visitor.locator('.registration-receipt')).toContainText(`當次餐食：${diet}`)
    expect(await visitor.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  }
  try{
    await register('東區','素食','正取')
    await visitor.screenshot({path:info.outputPath('public-confirmed.png'),fullPage:true})
    await page.getByRole('button',{name:'報名與設定',exact:true}).click()
    await expect(summary('正取／名額')).toContainText('1/1')
    await expect(summary('葷／素／未設定')).toContainText('0/1/0')
    const first=(await detail()).registrations.find((r:any)=>r.distinguishing_note==='東區'&&r.status==='confirmed')
    expect(first).toMatchObject({diet:'vegetarian',hard_level_snapshot:2,competition_level:2})
    await page.getByRole('button',{name:'排級數',exact:true}).click()
    await expect(area.locator(`[data-registration-id="${first.id}"]`)).toHaveCount(1)
    await expect(area.getByRole('button',{name:'素食 1 人',exact:true})).toBeVisible()
    const afterPublic=await state()
    expect(afterPublic.layout.columns.at(-1).level).toBe(2)
    const cell=afterPublic.layout.cells.find((c:any)=>c.registration_id===first.id)
    expect(cell.column_id).toBe(afterPublic.layout.columns.at(-1).id)
    observations.events.push({event:'existing-mode-buttons-refresh',confirmed:1,arrangementRows:afterPublic.rows.length,publicRegistrationRestoresMissingLevelColumn:2})
    await register('西區','葷食','候補')
    await expect(area.locator('.arrangement-cell')).toHaveCount(1)
    await page.getByRole('button',{name:'報名與設定',exact:true}).click()
    await expect(summary('候補')).toContainText('1')
    await expect(summary('葷／素／未設定')).toContainText('0/1/0')
    const second=(await detail()).registrations.find((r:any)=>r.distinguishing_note==='西區'&&r.status==='waitlisted')
    expect(second).toMatchObject({diet:'omnivore',hard_level_snapshot:8,competition_level:8})
    const roster=page.locator(info.project.name==='mobile'?'.mobile-registration-list':'.admin-roster-grid')
    await roster.getByRole('button',{name:new RegExp(`合成同名，正取，${first.queue_sequence} 號`)}).click()
    await expect(page.getByRole(info.project.name==='mobile'?'dialog':'region',{name:'報名管理操作'})).toContainText('東區')
    await page.getByRole('button',{name:'取消報名',exact:true}).click()
    await expect(summary('正取／名額')).toContainText('0/1')
    await expect(summary('待遞補')).toContainText('1')
    await page.getByRole('button',{name:'關閉',exact:true}).click()
    await page.getByRole('button',{name:'排級數',exact:true}).click()
    await expect(area.locator('.arrangement-cell')).toHaveCount(0)
    expect((await state()).rows).toHaveLength(0)
    await page.getByRole('button',{name:'報名與設定',exact:true}).click()
    await page.locator('.admin-roster-sidebar').getByRole('button',{name:'候補 1 人 展開',exact:true}).click()
    await page.locator('.admin-roster-sidebar').getByRole('button',{name:`${second.queue_sequence}. 合成同名 西區`,exact:true}).click()
    await expect(page.getByRole(info.project.name==='mobile'?'dialog':'region',{name:'報名管理操作'})).toContainText('西區')
    await page.getByRole('button',{name:'確認遞補',exact:true}).click()
    await expect(summary('正取／名額')).toContainText('1/1')
    await expect(summary('候補')).toContainText('0')
    await expect(summary('葷／素／未設定')).toContainText('1/0/0')
    await page.getByLabel('合成同名當次餐食',{exact:true}).selectOption('vegetarian')
    await expect(summary('葷／素／未設定')).toContainText('0/1/0')
    await page.getByRole('button',{name:'關閉',exact:true}).click()
    await page.getByRole('button',{name:'排級數',exact:true}).click()
    await expect(area.locator(`[data-registration-id="${second.id}"]`)).toHaveCount(1)
    await expect(area.getByRole('button',{name:'素食 1 人',exact:true})).toBeVisible()
    const promoted=(await state()).rows
    expect(promoted).toHaveLength(1)
    expect(promoted[0]).toMatchObject({registration_id:second.id,competition_level:8,diet:'vegetarian'})
    await page.screenshot({path:info.outputPath('admin-arrangement-after-promotion.png'),fullPage:true})
    observations.events.push({event:'cancel-promote-meal-change',cancelledExcludedFromArrangement:true,waitlistNotAutoPromoted:true,promotedRetainsCompetitionLevel:8,mealSyncedToArrangement:'vegetarian'})
    await register('東區','葷食','候補')
    await page.getByLabel('選擇比賽',{exact:true}).selectOption(other.id)
    await page.getByLabel('選擇比賽',{exact:true}).selectOption(comp.id)
    await expect(area.locator('.arrangement-cell')).toHaveCount(1)
    await page.getByRole('button',{name:'報名與設定',exact:true}).click()
    await expect(summary('候補')).toContainText('1')
    await expect(page.getByRole('button',{name:'已取消 1 人 展開',exact:true})).toBeVisible()
    const final=(await detail()).registrations
    const reentered=final.find((r:any)=>r.distinguishing_note==='東區'&&r.status==='waitlisted')
    expect(reentered.id).not.toBe(first.id)
    expect(reentered.queue_sequence).toBeGreaterThan(second.queue_sequence)
    expect(final.find((r:any)=>r.id===first.id).status).toBe('cancelled')
    await page.reload();await page.getByLabel('選擇比賽',{exact:true}).selectOption(comp.id)
    await page.getByRole('button',{name:'報名與設定',exact:true}).click()
    await expect(summary('正取／名額')).toContainText('1/1')
    await expect(summary('候補')).toContainText('1')
    const history=await(await page.request.get(endpoint+'/history')).json()
    expect(history.filter((h:any)=>h.actor_kind==='public'&&h.action==='create')).toHaveLength(3)
    expect(history.filter((h:any)=>h.actor_kind==='admin'&&h.action==='cancel')).toHaveLength(1)
    expect(history.filter((h:any)=>h.actor_kind==='admin'&&h.action==='promote')).toHaveLength(1)
    observations.events.push({event:'reregister-switch-and-full-reload',confirmed:1,waitlisted:1,cancelled:1,reentryUsesNewIdAndQueue:true,auditPublicCreates:3,auditAdminCancel:1,auditAdminPromote:1})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    expect(errors).toEqual([])
    await page.screenshot({path:info.outputPath('admin-final-linked-roster.png'),fullPage:true})
  }finally{
    observations.pageErrors=errors
    await writeFile(info.outputPath('linkage-observations.json'),JSON.stringify(observations,null,2))
    await visitorContext.close()
  }
})
