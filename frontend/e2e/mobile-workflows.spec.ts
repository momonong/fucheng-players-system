test('送出後連線中斷保留原請求，手機無法重複調整並可安全恢復', async ({ page }, info) => {
  const s = await setup(page, info)
  await activate(info, s.area.getByRole('button', { name: '名單操作', exact: true }))
  const writes: any[] = []
  let first = true
  await page.route('**/arrangement/operations', async route => {
    writes.push(route.request().postDataJSON())
    if (first) { first = false; await route.fetch(); await route.abort('failed') }
    else await route.continue()
  })
  const dialog = await openPlayer(page, info)
  await dialog.getByLabel('目標級數').selectOption('7')
  await activate(info, dialog.getByRole('button', { name: '確認調整' }))
  await expect(dialog.getByRole('button', { name: '確認調整' })).toBeDisabled()
  await activate(info, dialog.getByRole('button', { name: '返回名單' }))
  await expect(s.area.getByRole('button', { name: /操作 .*辨識0/ })).toBeDisabled()
  await expect(s.area.locator('.arrangement-recovery')).toContainText('結果尚未確認')
  await activate(info, s.area.getByRole('button', { name: '確認操作結果／原樣重試' }))
  await expect(s.area.locator('.arrangement-recovery')).toHaveCount(0)
  const result = await s.state()
  expect(result.rows.find((r: any) => r.registration_id === s.people[0].id).competition_level).toBe(7)
  expect(writes).toHaveLength(2); expect(writes[1]).toEqual(writes[0])
})

