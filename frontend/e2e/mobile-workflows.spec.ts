test('外來更新使手機舊操作遭拒，重新核對後不自動套用或覆寫', async ({ page }, info) => {
  const s = await setup(page, info)
  await activate(info, s.area.getByRole('button', { name: '名單操作', exact: true }))
  const dialog = await openPlayer(page, info)
  await dialog.getByLabel('調整方式').selectOption('swap')
  await dialog.getByLabel('目標選手').selectOption(s.people[1].id)
  const before = await s.state()
  const external = await page.request.post(s.endpoint + '/operations', { headers: s.headers, data: { request_id: crypto.randomUUID(), state_token: before.state_token, operation: { action: 'move_bottom', registration_id: s.people[0].id, level: 8 } } })
  expect(external.status()).toBe(200)
  const writes: any[] = []
  page.on('request', request => { if (request.url().endsWith('/arrangement/operations')) writes.push(request.postDataJSON()) })
  await activate(info, dialog.getByRole('button', { name: '確認調整' }))
  await expect(dialog.getByRole('button', { name: '確認調整' })).toBeDisabled()
  await activate(info, dialog.getByRole('button', { name: '返回名單' }))
  await activate(info, s.area.getByRole('button', { name: '重新讀取並核對', exact: true }))
  await expect(s.area.locator('.arrangement-recovery')).toHaveCount(0)
  expect(writes).toHaveLength(1)
  expect(writes[0].state_token).toBe(before.state_token)
  const after = await s.state()
  expect(after.rows.find((r: any) => r.registration_id === s.people[0].id).competition_level).toBe(8)
  expect(after.rows.find((r: any) => r.registration_id === s.people[1].id).competition_level).toBe(2)
})
