import { expect, test, type Page } from '@playwright/test'
import { randomBytes } from 'node:crypto'

const base = (process.env.FUCHENG_BASE_PATH ?? '').replace(/\/$/, '')
const url = (path: string) => `${base}${path}`
const newPassword = () => randomBytes(24).toString('base64url')
test.use({ actionTimeout: 10_000 })
const expectNotice = (page: Page, text: string) => expect(page.getByRole('status').filter({ hasText: text })).toHaveText(text)

async function login(page: Page, username: string, password: string) {
  await page.goto(url('/admin/admins'))
  await page.getByLabel('帳號', { exact: true }).fill(username)
  await page.getByLabel('密碼', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登入', exact: true }).click()
}

async function passwordFields(page: Page, password: string, currentPassword: string) {
  await page.getByLabel('新密碼', { exact: true }).fill(password)
  await page.getByLabel('再次輸入新密碼', { exact: true }).fill(password)
  await page.getByLabel('本人目前密碼', { exact: true }).fill(currentPassword)
}

test('管理員帳號完整生命週期、受限登入、session撤銷與衝突核對', async ({ page, browser }, info) => {
  test.setTimeout(60_000)
  const ownerPassword = process.env.FUCHENG_E2E_ADMIN_PASSWORD!
  const username = `合成管理員-${info.project.name}-${randomBytes(4).toString('hex')}`
  const displayName = `合成姓名-${info.project.name}`
  const initialPassword = newPassword()
  const firstPassword = newPassword()
  const resetPassword = newPassword()
  const secondPassword = newPassword()
  const finalPassword = newPassword()
  const peerContext = await browser.newContext({ baseURL: info.project.use.baseURL, viewport: info.project.use.viewport, isMobile: info.project.use.isMobile, hasTouch: info.project.use.hasTouch })
  const peer = await peerContext.newPage()
  try {
    await login(page, 'e2e-admin', ownerPassword)
    await expect(page.getByRole('heading', { name: '管理員管理', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: '管理員管理', exact: true })).toHaveAttribute('href', url('/admin/admins'))
    const owner = page.locator('[data-admin-username="e2e-admin"]')
    await expect(owner).toContainText('本人')
    await expect(owner.getByRole('button', { name: '停用帳號' })).toHaveCount(0)
    await expect(owner.getByRole('button', { name: '重設密碼' })).toHaveCount(0)
    await expect(page.getByText(/版本|revision|schema/)).toHaveCount(0)

    await page.getByRole('button', { name: '新增管理員', exact: true }).click()
    await page.getByLabel('新管理員帳號', { exact: true }).fill(username)
    await page.getByLabel('管理員姓名（選填）', { exact: true }).fill(displayName)
    await passwordFields(page, initialPassword, newPassword())
    await page.getByRole('button', { name: '確認新增管理員', exact: true }).click()
    await expect(page.getByRole('alert')).toBeVisible()
    await expect(page.locator(`[data-admin-username="${username}"]`)).toHaveCount(0)
    await page.getByLabel('本人目前密碼', { exact: true }).fill(ownerPassword)
    await page.getByRole('button', { name: '確認新增管理員', exact: true }).click()
    await expectNotice(page, '管理員已新增，首次登入時須更換密碼。')
    const account = page.locator(`[data-admin-username="${username}"]`)
    await expect(account).toContainText('首次登入需更換密碼')
    await expect(account).toContainText(displayName)
    await expect(page.locator('.admin-account-history')).toContainText(username)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`admin-management-${info.project.name}.png`), fullPage: true })

    await login(peer, username, initialPassword)
    await expect(peer.getByRole('heading', { name: '請先更換密碼', exact: true })).toBeVisible()
    await expect(peer.getByText(displayName, { exact: false })).toBeVisible()
    await expect(peer.getByRole('link', { name: '管理員管理', exact: true })).toHaveCount(0)
    expect((await peer.request.get(url('/api/admin/admins'))).status()).toBe(403)
    expect((await peer.request.get(url('/api/admin/members'))).status()).toBe(403)
    await peer.getByRole('button', { name: '登出', exact: true }).click()
    await expect(peer.getByRole('heading', { name: '管理員登入', exact: true })).toBeVisible()
    expect((await peer.request.get(url('/api/auth/me'))).status()).toBe(401)
    await login(peer, username, initialPassword)
    await expect(peer.getByRole('heading', { name: '請先更換密碼', exact: true })).toBeVisible()
    await peer.reload()
    await expect(peer.getByRole('heading', { name: '請先更換密碼', exact: true })).toBeVisible()
    await peer.screenshot({ path: info.outputPath(`required-password-${info.project.name}.png`), fullPage: true })
    await passwordFields(peer, firstPassword, initialPassword)
    await peer.getByLabel('再次輸入新密碼', { exact: true }).fill(newPassword())
    await peer.getByRole('button', { name: '更新密碼並重新登入', exact: true }).click()
    await expect(peer.getByRole('alert')).toContainText('兩次輸入的新密碼不一致')
    await peer.getByLabel('再次輸入新密碼', { exact: true }).fill(firstPassword)
    await peer.getByRole('button', { name: '更新密碼並重新登入', exact: true }).click()
    await expect(peer.getByRole('heading', { name: '管理員登入', exact: true })).toBeVisible()
    await expectNotice(peer, '密碼已更新，請使用新密碼重新登入。')
    expect((await peer.request.get(url('/api/auth/me'))).status()).toBe(401)
    await login(peer, username, initialPassword)
    await expect(peer.getByRole('alert')).toBeVisible()
    await login(peer, username, firstPassword)
    await expect(peer.getByRole('heading', { name: '管理員管理', exact: true })).toBeVisible()
    for (const path of ['/admin', '/admin/competitions', '/admin/announcements', '/admin/system/deployment-report', '/admin/roster', '/admin/admins']) {
      await peer.goto(url(path))
      await expect(peer.locator('.admin-username')).toHaveText(`${displayName}（${username}）`)
    }
    await expect(peer.locator(`[data-admin-username="${username}"]`)).toContainText(displayName)

    await account.getByRole('button', { name: '重設密碼', exact: true }).click()
    await passwordFields(page, resetPassword, ownerPassword)
    await page.getByRole('button', { name: '確認重設密碼', exact: true }).click()
    // The peer changed its own password after this list was loaded.
    await expect(page.getByRole('alert')).toContainText('資料已更新')
    await page.getByRole('button', { name: '核對最新帳號', exact: true }).click()
    await page.getByLabel('本人目前密碼', { exact: true }).fill(ownerPassword)
    await page.getByRole('button', { name: '確認重設密碼', exact: true }).click()
    await expectNotice(page, '密碼已重設，該帳號須重新登入並更換密碼。')
    expect((await peer.request.get(url('/api/auth/me'))).status()).toBe(401)
    await login(peer, username, resetPassword)
    await expect(peer.getByRole('heading', { name: '請先更換密碼', exact: true })).toBeVisible()
    await passwordFields(peer, secondPassword, resetPassword)
    await peer.getByRole('button', { name: '更新密碼並重新登入', exact: true }).click()
    await expect(peer.getByRole('heading', { name: '管理員登入', exact: true })).toBeVisible()
    await login(peer, username, secondPassword)
    await expect(peer.getByRole('heading', { name: '管理員管理', exact: true })).toBeVisible()

    await account.getByRole('button', { name: '停用帳號', exact: true }).click()
    await page.getByLabel('本人目前密碼', { exact: true }).fill(ownerPassword)
    await page.getByRole('button', { name: '確認停用帳號', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('資料已更新')
    await expect(page.getByRole('button', { name: '確認停用帳號', exact: true })).toBeDisabled()
    await expect(page.getByLabel('本人目前密碼', { exact: true })).toBeEmpty()
    await page.getByRole('button', { name: '核對最新帳號', exact: true }).click()
    await expect(page.getByRole('button', { name: '確認停用帳號', exact: true })).toBeEnabled()
    await page.getByLabel('本人目前密碼', { exact: true }).fill(ownerPassword)
    await page.getByRole('button', { name: '確認停用帳號', exact: true }).click()
    await expectNotice(page, '管理員已停用，原登入已失效。')
    await expect(account).toContainText('停用')
    expect((await peer.request.get(url('/api/auth/me'))).status()).toBe(401)
    await login(peer, username, secondPassword)
    await expect(peer.getByRole('alert')).toBeVisible()
    await account.getByRole('button', { name: '啟用帳號', exact: true }).click()
    await page.getByLabel('本人目前密碼', { exact: true }).fill(ownerPassword)
    await page.getByRole('button', { name: '確認啟用帳號', exact: true }).click()
    await expectNotice(page, '管理員已啟用。')
    await login(peer, username, secondPassword)
    await expect(peer.getByRole('heading', { name: '管理員管理', exact: true })).toBeVisible()

    await peer.getByRole('button', { name: '修改我的密碼', exact: true }).click()
    await passwordFields(peer, finalPassword, secondPassword)
    await peer.getByRole('button', { name: '更新密碼並重新登入', exact: true }).click()
    await expect(peer.getByRole('heading', { name: '管理員登入', exact: true })).toBeVisible()
    await login(peer, username, finalPassword)
    await expect(peer.getByRole('heading', { name: '管理員管理', exact: true })).toBeVisible()
    await expect(peer.locator('.admin-account-history')).toContainText('本人修改密碼')
    await expect.poll(() => peer.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await peer.screenshot({ path: info.outputPath(`admin-management-complete-${info.project.name}.png`), fullPage: true })
    await peer.getByRole('button', { name: '登出', exact: true }).click()
    await expect(peer.getByRole('heading', { name: '管理員登入', exact: true })).toBeVisible()
    expect((await peer.request.get(url('/api/auth/me'))).status()).toBe(401)
  } finally { await peerContext.close() }
})
